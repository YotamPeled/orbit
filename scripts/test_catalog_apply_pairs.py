#!/usr/bin/env python3
"""catalog-sync writes applyPairs Applications under clusters/orbit/, not apps/.

Two-pair fixture: alpha/dev moves, alpha/prod stays. Dashboards, probes and
namespaces.yaml stay under clusters/apps/. The committed placement golden is
the oracle for those stable paths.
"""
import pathlib
import shutil
import subprocess
import sys
import tempfile
import unittest

import yaml


ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "scripts" / "catalog-sync.py"
CHART = ROOT / "charts" / "service"
TESTDATA = ROOT / "scripts" / "testdata" / "catalog-apply-pairs"
EXPECTED_PLACEMENT = TESTDATA / "expected" / "placement.txt"
ORBITD_NAMESPACE = (
    ROOT / "template" / "provisioning" / "clusters" / "platform"
    / "config" / "orbitd" / "namespace.yaml")


def _stage_orbitd_namespace(root: pathlib.Path) -> None:
    dest = (root / "template" / "provisioning" / "clusters" / "platform"
            / "config" / "orbitd" / "namespace.yaml")
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ORBITD_NAMESPACE, dest)


class Sandbox:
    def __init__(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.tmp.name)
        (self.root / "scripts").mkdir()
        shutil.copy2(GENERATOR, self.root / "scripts" / "catalog-sync.py")
        (self.root / "charts").mkdir()
        shutil.copytree(CHART, self.root / "charts" / "service")
        shutil.copytree(TESTDATA / "catalog", self.root / "catalog")
        shutil.copytree(TESTDATA / "instance", self.root / "instance")
        (self.root / "clusters" / "apps").mkdir(parents=True)
        _stage_orbitd_namespace(self.root)

    def close(self):
        self.tmp.cleanup()

    def generate(self):
        return subprocess.run(
            [sys.executable, "scripts/catalog-sync.py"], cwd=self.root,
            capture_output=True, text=True)

    def write_apply_pairs(self, pairs):
        path = self.root / "instance" / "config.yaml"
        cfg = yaml.safe_load(path.read_text()) or {}
        if pairs:
            cfg.setdefault("orbitd", {})["applyPairs"] = list(pairs)
        else:
            (cfg.get("orbitd") or {}).pop("applyPairs", None)
            if cfg.get("orbitd") == {}:
                cfg.pop("orbitd", None)
        path.write_text(yaml.safe_dump(cfg, sort_keys=False))

    def yaml_paths(self):
        out = []
        for base in (self.root / "clusters" / "apps",
                     self.root / "clusters" / "orbit"):
            if not base.is_dir():
                continue
            for path in sorted(base.glob("*.yaml")):
                out.append(str(path.relative_to(self.root)))
        return out


class CatalogApplyPairsTest(unittest.TestCase):
    def setUp(self):
        self.box = Sandbox()

    def tearDown(self):
        self.box.close()

    def assert_generated(self):
        proc = self.box.generate()
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)
        return proc

    def test_one_pair_moves_to_orbit_the_other_stays_in_apps(self):
        """The break: both Applications stay in clusters/apps, or dashboards
        and namespaces.yaml follow the moved pair into clusters/orbit/."""
        self.assert_generated()
        orbit = self.box.root / "clusters" / "orbit" / "alpha-dev.yaml"
        apps_dev = self.box.root / "clusters" / "apps" / "alpha-dev.yaml"
        apps_prod = self.box.root / "clusters" / "apps" / "alpha-prod.yaml"
        self.assertTrue(orbit.is_file(), "alpha/dev Application was not written to clusters/orbit/")
        self.assertFalse(apps_dev.exists(), "alpha/dev Application was left in clusters/apps/")
        self.assertTrue(apps_prod.is_file(), "alpha/prod Application left clusters/apps/")
        self.assertTrue((self.box.root / "clusters" / "apps" / "dashboard-alpha-dev.yaml").is_file())
        self.assertTrue((self.box.root / "clusters" / "apps" / "namespaces.yaml").is_file())
        banner = "# GENERATED by scripts/catalog-sync.py from catalog/projects.yaml — do not edit.\n"
        self.assertTrue(orbit.read_text().startswith(banner))
        self.assertTrue(apps_prod.read_text().startswith(banner))
        kinds = [d.get("kind") for d in yaml.safe_load_all(orbit.read_text()) if d]
        self.assertIn("Application", kinds)

    def test_moved_application_matches_the_apps_render_and_prunes_the_old_file(self):
        """The break: orbit gets different bytes, or the apps file is left
        behind so ArgoCD keeps applying the pair."""
        self.box.write_apply_pairs([])
        self.assert_generated()
        apps_dev = self.box.root / "clusters" / "apps" / "alpha-dev.yaml"
        baseline = apps_dev.read_text()
        self.box.write_apply_pairs(["alpha/dev"])
        proc = self.assert_generated()
        self.assertIn("pruned clusters/apps/alpha-dev.yaml", proc.stdout)
        orbit = self.box.root / "clusters" / "orbit" / "alpha-dev.yaml"
        self.assertEqual(orbit.read_text(), baseline)
        self.assertFalse(apps_dev.exists())

    def test_placement_matches_the_committed_golden(self):
        self.assert_generated()
        expected = {line.strip() for line in EXPECTED_PLACEMENT.read_text().splitlines()
                    if line.strip()}
        got = set(self.box.yaml_paths())
        missing = expected - got
        self.assertFalse(missing, f"expected paths missing: {sorted(missing)}")
        extra_stable = {p for p in (got - expected)
                        if not pathlib.Path(p).name.startswith("tenant-probe-")}
        self.assertFalse(extra_stable, f"unexpected non-probe paths: {sorted(extra_stable)}")
        probes = [p for p in got if pathlib.Path(p).name.startswith("tenant-probe-")]
        self.assertTrue(probes, "tenant Probe was not generated")
        self.assertTrue(all(p.startswith("clusters/apps/") for p in probes),
                        f"tenant Probe left clusters/apps/: {probes}")


class GeneratedPathIdentityTest(unittest.TestCase):
    def test_generated_path_identity_kind(self):
        import importlib.util
        spec = importlib.util.spec_from_file_location("catalog_sync_apply_pairs", GENERATOR)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        self.assertEqual(module.generated_path_identity("clusters/orbit/alpha-dev.yaml"),
                         "clusters/orbit path")
        self.assertEqual(module.generated_path_identity("clusters/apps/alpha-prod.yaml"),
                         "clusters/apps path")


if __name__ == "__main__":
    unittest.main(verbosity=2)
