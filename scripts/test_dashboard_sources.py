#!/usr/bin/env python3
"""
The generated dashboards after the eBPF floor is deleted — run as
`python3 scripts/test_dashboard_sources.py`. No cluster, no network.

WHY. Every generated RED dashboard draws from the eBPF instrumentation's uniform
semconv metrics (`http_server_request_duration_seconds_*`, and one panel that counts the
pods the floor sees). That floor is 2.8k series and 397 MiB of the platform's memory
budget, and phase 8 deletes it. Measured on the reference instance, everything the web
panels show is ALREADY in Traefik's own metrics, keyed by the service label Traefik
gives each Kubernetes Service; everything the worker panels can show comes from Tempo's
span-metrics generator, which phase 8b already runs.

WHAT THIS PINS.
  * No dashboard, rule, app or stage references the eBPF floor any more.
  * A web component's rate/errors/latency come from Traefik, selected by that
    component's own service label — `<namespace>-<service>-<port>@kubernetes`, where the
    Service is `<project>-<component>` and its port is named http. A dashboard that
    selects the whole namespace instead cannot tell two components apart.
  * A worker component appears through span-metrics, selected by its own name. Workers
    emit nothing until the product emits spans, so the panel must exist and be EMPTY
    rather than be omitted — an omitted panel is indistinguishable from a component
    nobody deployed.
  * Every environment gets the two panels that need no instrumentation at all: container
    restarts and OOM kills, from kube-state-metrics.
  * Every panel's query is scoped to the project's own namespace or service. An unscoped
    query on a shared Prometheus draws another tenant's traffic.

The fixture is the catalog-quota testdata (a project with a web component, a worker and a
database, plus a project with only a web component), generated by the repository's real
catalog-sync.py in a temporary tree.
"""
import json
import pathlib
import re
import subprocess
import sys
import unittest

import yaml

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
_BYTECODE, sys.dont_write_bytecode = sys.dont_write_bytecode, True
from test_catalog_quota import ROOT, Sandbox  # noqa: E402
sys.dont_write_bytecode = _BYTECODE

# The floor being deleted, by every name it is known by in the tree.
FLOOR = re.compile(r"obi|opentelemetry-ebpf|http_server_request_duration_seconds", re.I)

# Where a dashboard is allowed to come from now.
TRAEFIK = re.compile(r"traefik_service_(requests_total|request_duration_seconds_bucket)")
SPANS = re.compile(r"traces_spanmetrics_\w+")
RESTARTS = "kube_pod_container_status_restarts_total"
OOM = "kube_pod_container_status_last_terminated_reason"


def dashboards(box):
    """{(project, env): dashboard dict} from the generated ConfigMaps."""
    out = {}
    for path in sorted((box.root / "clusters" / "apps").glob("dashboard-*.yaml")):
        for doc in yaml.safe_load_all(path.read_text()):
            if not doc or doc.get("kind") != "ConfigMap":
                continue
            for name, blob in (doc.get("data") or {}).items():
                dash = json.loads(blob)
                m = re.match(r"red-(.+)-(dev|prod)\.json$", name)
                assert m, f"unexpected dashboard file {name}"
                out[(m.group(1), m.group(2))] = dash
    return out


def exprs(dash):
    return [t["expr"] for panel in dash["panels"] for t in panel.get("targets", [])]


def titled(dash, needle):
    return [p for p in dash["panels"] if needle.lower() in p["title"].lower()]


class _Generated(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.box = Sandbox()
        proc = cls.box.generate()
        if proc.returncode != 0:
            cls.box.close()
            raise AssertionError("catalog-sync failed:\n" + proc.stdout + proc.stderr)
        cls.dash = dashboards(cls.box)

    @classmethod
    def tearDownClass(cls):
        cls.box.close()


class WebPanelsTest(_Generated):
    """A web component's RED comes from the ingress that already sees it."""

    def test_the_ebpf_floor_is_gone_from_every_query(self):
        offenders = []
        for (pid, env), dash in self.dash.items():
            for e in exprs(dash):
                if FLOOR.search(e):
                    offenders.append(f"{pid}/{env}: {e[:120]}")
        self.assertEqual(offenders, [],
                         "a panel still queries the deleted eBPF floor:\n" + "\n".join(offenders))

    def test_the_rate_panel_reads_traefik(self):
        dash = self.dash[("widgets", "prod")]
        hits = [e for e in exprs(dash) if TRAEFIK.search(e)]
        self.assertTrue(hits, "no panel reads Traefik's own metrics:\n"
                              + "\n".join(exprs(dash)))

    def test_each_web_component_is_selected_by_its_own_service(self):
        """`<namespace>-<service>-<port>@kubernetes`, the label Traefik gives the Service
        the chart renders as <project>-<component> on port http."""
        dash = self.dash[("widgets", "prod")]
        want = re.compile(r"widgets-prod-widgets-web-[a-z0-9-]+@kubernetes")
        hits = [e for e in exprs(dash) if want.search(e)]
        self.assertTrue(hits,
                        "no panel selects the web component's own Traefik service label — a "
                        "namespace-wide query cannot tell two components apart:\n"
                        + "\n".join(e for e in exprs(dash) if TRAEFIK.search(e)))

    def test_errors_and_latency_come_from_traefik_too(self):
        dash = self.dash[("widgets", "prod")]
        err = [e for e in exprs(dash) if "traefik_service_requests_total" in e and "5" in e]
        self.assertTrue(err, "no 5xx panel over Traefik's request counter")
        lat = [e for e in exprs(dash) if "traefik_service_request_duration_seconds_bucket" in e]
        self.assertTrue(lat, "no latency panel over Traefik's duration histogram")

    def test_a_project_with_no_worker_still_gets_its_web_panels(self):
        dash = self.dash[("bare", "prod")]
        self.assertTrue([e for e in exprs(dash) if TRAEFIK.search(e)],
                        "the web-only project lost its RED panels")


class WorkerPanelsTest(_Generated):
    """A worker has no ingress. Span-metrics is the only thing that can see it."""

    def test_the_worker_has_a_panel(self):
        dash = self.dash[("widgets", "prod")]
        hits = [e for e in exprs(dash) if SPANS.search(e)]
        self.assertTrue(hits,
                        "the worker component has no span-metrics panel — with the eBPF floor "
                        "gone it is invisible, and an omitted panel reads as a component "
                        "nobody deployed:\n" + "\n".join(exprs(dash)))

    def test_the_worker_panel_names_the_worker(self):
        dash = self.dash[("widgets", "prod")]
        hits = [e for e in exprs(dash) if SPANS.search(e) and "importer" in e]
        self.assertTrue(hits,
                        "the span-metrics panel does not select the worker by name — it draws "
                        "every service's spans:\n"
                        + "\n".join(e for e in exprs(dash) if SPANS.search(e)))

    def test_a_project_with_no_worker_has_no_worker_panel(self):
        dash = self.dash[("bare", "prod")]
        self.assertEqual([e for e in exprs(dash) if SPANS.search(e)], [],
                         "a project with no worker got a span-metrics panel")


class HealthPanelsTest(_Generated):
    """The two panels that need no instrumentation at all."""

    def test_every_dashboard_shows_restarts(self):
        for key, dash in self.dash.items():
            hits = [e for e in exprs(dash) if RESTARTS in e]
            self.assertTrue(hits, f"{key[0]}/{key[1]} has no container-restart panel")

    def test_every_dashboard_shows_oom_kills(self):
        for key, dash in self.dash.items():
            hits = [e for e in exprs(dash) if OOM in e and "OOMKilled" in e]
            self.assertTrue(hits, f"{key[0]}/{key[1]} has no OOMKilled panel")

    def test_the_health_panels_are_scoped_to_the_project(self):
        for (pid, env), dash in self.dash.items():
            for e in exprs(dash):
                if RESTARTS in e or OOM in e:
                    self.assertIn(f"{pid}-{env}", e,
                                  f"{pid}/{env}: a health panel is not scoped to the "
                                  f"project's namespace: {e[:140]}")


class EveryPanelTest(_Generated):
    """Properties that hold for every panel, whatever it draws."""

    def test_no_query_is_unscoped(self):
        offenders = []
        for (pid, env), dash in self.dash.items():
            for e in exprs(dash):
                if pid not in e and f"{pid}-{env}" not in e:
                    offenders.append(f"{pid}/{env}: {e[:140]}")
        self.assertEqual(offenders, [],
                         "a panel query names no project — on a shared Prometheus it draws "
                         "another tenant's traffic:\n" + "\n".join(offenders))

    def test_every_panel_is_addressable_and_has_a_query(self):
        for (pid, env), dash in self.dash.items():
            seen = set()
            for panel in dash["panels"]:
                self.assertTrue(panel.get("title"), f"{pid}/{env}: a panel has no title")
                self.assertIn("id", panel, f"{pid}/{env}: {panel.get('title')} has no id")
                self.assertNotIn(panel["id"], seen, f"{pid}/{env}: duplicate panel id")
                seen.add(panel["id"])
                self.assertTrue(panel.get("targets"),
                                f"{pid}/{env}: {panel['title']} draws nothing")

    def test_every_query_balances(self):
        for (pid, env), dash in self.dash.items():
            for e in exprs(dash):
                self.assertEqual(e.count("("), e.count(")"), f"{pid}/{env}: {e[:140]}")
                self.assertEqual(e.count("{"), e.count("}"), f"{pid}/{env}: {e[:140]}")


class FloorRemovedTest(unittest.TestCase):
    """The floor leaves the tree, not just the dashboards."""

    LIVE = ("template", "charts", "scripts", ".claude")
    ALLOWED = re.compile(r"(^|/)(docs|CHANGELOG)|testdata/|crds/|test_dashboard_sources\.py")

    def tracked(self):
        out = subprocess.run(["git", "ls-files"] + list(self.LIVE), cwd=ROOT,
                             capture_output=True, text=True, check=True)
        return [p for p in out.stdout.split() if not self.ALLOWED.search(p)]

    def test_the_app_is_deleted(self):
        self.assertFalse((ROOT / "template" / "clusters" / "platform" / "apps" / "obi.yaml").exists(),
                         "the eBPF floor's Application file is still shipped")

    def test_nothing_live_still_names_it(self):
        word = re.compile(r"\bobi\b|obi-opentelemetry-ebpf|opentelemetry-ebpf-instrumentation", re.I)
        hits = []
        for rel in self.tracked():
            p = ROOT / rel
            try:
                text = p.read_text()
            except (UnicodeDecodeError, OSError):
                continue
            for n, line in enumerate(text.splitlines(), 1):
                if word.search(line):
                    hits.append(f"{rel}:{n}: {line.strip()[:110]}")
        self.assertEqual(hits, [], "the deleted floor is still named in live files:\n"
                                   + "\n".join(hits))


if __name__ == "__main__":
    unittest.main(verbosity=2)
